#!/usr/bin/env bash
# Fork lab control (W02). DISPOSABLE, LOCALHOST ONLY, SYNTHETIC DATA ONLY. Never point this at production.
#   lab.sh up       generate .env.lab (first run), start portabase (dashboard+db+minio), arcane, demo stack, seed
#   lab.sh agent    start the Portabase agent (needs LAB_EDGE_KEY in .env.lab; enroll the agent in the dashboard first)
#   lab.sh status   show lab containers + published ports
#   lab.sh down     stop everything (volumes kept)
#   lab.sh reset    stop and DELETE all lab volumes/networks (compose projects forklab-* only)
set -euo pipefail
LAB="$(cd "$(dirname "$0")" && pwd)"
cd "$LAB"
ENVF="$LAB/.env.lab"
PORTABASE=(docker compose --env-file "$ENVF" -f compose.portabase.yml)
ARCANE=(docker compose --env-file "$ENVF" -f compose.arcane.yml)
AGENT=(docker compose --env-file "$ENVF" -f portabase-agent/compose.yml)
DEMO=(docker compose -f demo-stack/compose.yml -f demo-stack/compose.override.yml)

rand() { openssl rand -hex "${1:-16}"; }

gen_env() {
  [ -f "$ENVF" ] && return 0
  umask 077
  {
    echo "# generated by lab.sh $(date -u +%FT%TZ); lab-only, git-ignored, never commit"
    echo "LAB_DB_PASSWORD=$(rand 16)"
    echo "LAB_PROJECT_SECRET=$(rand 24)"
    echo "LAB_ADMIN_EMAIL=admin@lab.invalid"
    echo "LAB_ADMIN_PASSWORD=Lab-$(rand 12)"
    echo "LAB_ARCANE_ENCRYPTION_KEY=$(rand 32)"
    echo "LAB_MINIO_ROOT_USER=labroot$(rand 3)"
    echo "LAB_MINIO_ROOT_PASSWORD=$(rand 16)"
    echo "LAB_S3_AGENT_KEY=agent$(rand 4)"
    echo "LAB_S3_AGENT_SECRET=$(rand 16)"
    echo "LAB_S3_PULL_KEY=pull$(rand 4)"
    echo "LAB_S3_PULL_SECRET=$(rand 16)"
    echo "LAB_DIR=$LAB"
    echo "LAB_EDGE_KEY="
  } > "$ENVF"
  echo "generated $ENVF (git-ignored)"
}

wait_http() { # url, seconds
  local end=$((SECONDS + $2))
  until curl -fsS -o /dev/null "$1" 2>/dev/null; do
    [ $SECONDS -ge $end ] && { echo "timeout waiting for $1" >&2; return 1; }
    sleep 2
  done
}

nets() {
  docker network inspect forklab_net >/dev/null 2>&1 || docker network create forklab_net >/dev/null
  docker network inspect lab_proxy >/dev/null 2>&1 || docker network create lab_proxy >/dev/null
}

case "${1:-}" in
  up)
    gen_env; nets
    "${PORTABASE[@]}" up -d
    "${ARCANE[@]}" up -d arcane
    bash demo-stack/seed.sh --verify >/dev/null
    wait_http http://forklab-dashboard.localhost:18887/api/health 180
    wait_http http://127.0.0.1:13552/api/health 120
    echo "dashboard http://forklab-dashboard.localhost:18887  arcane http://127.0.0.1:13552  minio-console http://127.0.0.1:19001  demo http://127.0.0.1:18080"
    ;;
  agent)
    gen_env; nets
    grep -Eq "^LAB_EDGE_KEY=.+" "$ENVF" || { echo "LAB_EDGE_KEY empty: enroll the agent in the dashboard, put its edge key in .env.lab" >&2; exit 1; }
    # optional variants: lab.sh agent attach-demo-net host-bind  -> portabase-agent/override.<variant>.yml (see ADR-001)
    FILES=(-f portabase-agent/compose.yml)
    for v in "${@:2}"; do FILES+=(-f "portabase-agent/override.$v.yml"); done
    docker compose --env-file "$ENVF" "${FILES[@]}" up -d --force-recreate ;;
  edge-key)
    # store the agent edge key shown by the dashboard (lab-only secret) in the git-ignored env file
    gen_env
    [ -n "${2:-}" ] || { echo "usage: lab.sh edge-key <EDGE_KEY>" >&2; exit 2; }
    sed -i "s|^LAB_EDGE_KEY=.*|LAB_EDGE_KEY=$2|" "$ENVF" ;;
  status) docker ps --filter "name=forklab" --format 'table {{.Names}}\t{{.Status}}\t{{.Ports}}' ;;
  down)
    "${AGENT[@]}" down 2>/dev/null || true
    "${ARCANE[@]}" down 2>/dev/null || true
    "${PORTABASE[@]}" down 2>/dev/null || true
    "${DEMO[@]}" down 2>/dev/null || true
    ;;
  reset)
    gen_env
    "${AGENT[@]}" down -v 2>/dev/null || true
    "${ARCANE[@]}" down -v 2>/dev/null || true
    "${PORTABASE[@]}" down -v 2>/dev/null || true
    "${DEMO[@]}" down -v 2>/dev/null || true
    docker network rm forklab_net lab_proxy >/dev/null 2>&1 || true
    ;;
  *) sed -n '2,8p' "$0"; exit 2 ;;
esac

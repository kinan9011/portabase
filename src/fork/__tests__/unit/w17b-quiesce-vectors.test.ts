import {readFileSync, writeFileSync} from "node:fs";
import {describe, expect, it} from "vitest";
import {QuiescePayloadSchema, QuiesceStartPayloadSchema} from "@/fork/quiesce/payload";

/**
 * Cross-language payload vectors (W17b). The dashboard schema decides `accept` for each case; the agent's `src/fork/tests/quiesce_vectors.json` consumer
 * (`quiesce::tests::dashboard_vectors`) must reach the same verdict with its serde + `validate` (`payload_invalid` on every refusal).
 * Generator: `W17B_VECTORS_OUT=<agent>/src/fork/tests/quiesce_vectors.json pnpm exec vitest run --project unit w17b-quiesce-vectors`.
 * Without the variable the committed copy at `$W17B_AGENT_CLONE/src/fork/tests/quiesce_vectors.json` is diffed (when set).
 */
const U = "11111111-1111-4111-8111-111111111111";
const t = (service: string, container_id: string) => ({service, container_id});
const base = {v: 1, run_id: U, stack_id: U, project: "forklab-quiesce", targets: [t("web", "0123456789ab"), t("db", "fedcba987654")], max_stop_seconds: 600, stop_timeout_cap_seconds: 120, start_timeout_seconds: 180, dry_run: false};
type Case = {name: string; type: "quiesce" | "quiesce_start"; payload: unknown; accept: boolean};
const cases: Case[] = [
    {name: "valid_two_targets", type: "quiesce", payload: base, accept: true},
    {name: "valid_full_ids_dry_run", type: "quiesce", payload: {...base, dry_run: true, targets: [t("web", "a".repeat(64))]}, accept: true},
    {name: "valid_bounds_low", type: "quiesce", payload: {...base, max_stop_seconds: 60, stop_timeout_cap_seconds: 10, start_timeout_seconds: 30}, accept: true},
    {name: "valid_bounds_high", type: "quiesce", payload: {...base, max_stop_seconds: 3600, stop_timeout_cap_seconds: 300, start_timeout_seconds: 600}, accept: true},
    {name: "valid_32_targets", type: "quiesce", payload: {...base, targets: Array.from({length: 32}, (_, i) => t(`s${i}`, i.toString(16).padStart(12, "0")))}, accept: true},
    {name: "unknown_field_command", type: "quiesce", payload: {...base, command: "rm -rf /"}, accept: false},
    {name: "unknown_field_image", type: "quiesce", payload: {...base, image: "x"}, accept: false},
    {name: "unknown_target_field_name", type: "quiesce", payload: {...base, targets: [{...t("web", "0123456789ab"), name: "web-1"}]}, accept: false},
    {name: "zero_targets", type: "quiesce", payload: {...base, targets: []}, accept: false},
    {name: "33_targets", type: "quiesce", payload: {...base, targets: Array.from({length: 33}, (_, i) => t(`s${i}`, i.toString(16).padStart(12, "0")))}, accept: false},
    {name: "duplicate_service", type: "quiesce", payload: {...base, targets: [t("web", "0123456789ab"), t("web", "fedcba987654")]}, accept: false},
    {name: "duplicate_container", type: "quiesce", payload: {...base, targets: [t("web", "0123456789ab"), t("db", "0123456789ab")]}, accept: false},
    {name: "short_container_id", type: "quiesce", payload: {...base, targets: [t("web", "0123456789a")]}, accept: false},
    {name: "uppercase_container_id", type: "quiesce", payload: {...base, targets: [t("web", "0123456789AB")]}, accept: false},
    {name: "shell_in_service", type: "quiesce", payload: {...base, targets: [t("web;id", "0123456789ab")]}, accept: false},
    {name: "bad_project", type: "quiesce", payload: {...base, project: "Bad_Project"}, accept: false},
    {name: "max_stop_59", type: "quiesce", payload: {...base, max_stop_seconds: 59}, accept: false},
    {name: "max_stop_3601", type: "quiesce", payload: {...base, max_stop_seconds: 3601}, accept: false},
    {name: "stop_cap_9", type: "quiesce", payload: {...base, stop_timeout_cap_seconds: 9}, accept: false},
    {name: "start_timeout_601", type: "quiesce", payload: {...base, start_timeout_seconds: 601}, accept: false},
    {name: "version_2", type: "quiesce", payload: {...base, v: 2}, accept: false},
    {name: "bad_run_id", type: "quiesce", payload: {...base, run_id: "not-a-uuid"}, accept: false},
    {name: "start_valid", type: "quiesce_start", payload: {v: 1, quiesce_task_id: U, project: "forklab-quiesce"}, accept: true},
    {name: "start_with_ids", type: "quiesce_start", payload: {v: 1, quiesce_task_id: U, project: "p", container_ids: ["0123456789ab"]}, accept: false},
    {name: "start_bad_task_id", type: "quiesce_start", payload: {v: 1, quiesce_task_id: "../../x", project: "p"}, accept: false},
];

describe("W17b payload vectors", () => {
    it("the dashboard schema decides every case as recorded", () => {
        for (const c of cases) {
            const r = (c.type === "quiesce" ? QuiescePayloadSchema : QuiesceStartPayloadSchema).safeParse(c.payload);
            expect(r.success, c.name).toBe(c.accept);
        }
        expect(cases.length).toBeGreaterThanOrEqual(12);
    });
    const file = {note: "Generated by the dashboard test w17b-quiesce-vectors; the agent must accept/refuse exactly as recorded (a refusal is `payload_invalid`).", cases};
    it("writes / diffs the agent copy", () => {
        const out = process.env.W17B_VECTORS_OUT;
        if (out) { writeFileSync(out, `${JSON.stringify(file, null, 2)}\n`); return; }
        const clone = process.env.W17B_AGENT_CLONE;
        if (clone) expect(JSON.parse(readFileSync(`${clone}/src/fork/tests/quiesce_vectors.json`, "utf8"))).toEqual(file);
    });
});
